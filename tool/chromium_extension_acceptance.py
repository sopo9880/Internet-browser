#!/usr/bin/env python3
"""Fail-closed Android Chromium / AdBlock acceptance for the v0.2.0 release.

The report must be generated by instrumented tests against the actual APK
and the actual user-required Chrome Web Store extension. Storing a manifest
or running a built-in ad blocker is not a substitute for native execution.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


REQUIRED_EXTENSION_ID = "gighmmpiobklfepjocnamgkkbiglidom"
REQUIRED_CHECKS = (
    "native_chromium_engine",
    "manifest_v3_loaded",
    "chrome_web_store_installed",
    "extension_id_matches",
    "extension_service_worker_activated",
    "declarative_net_request_blocks_ads",
    "permission_prompt_works",
    "extension_action_popup_works",
    "settings_persist_after_restart",
    "rules_apply_to_real_page_requests",
    "manual_allowlist_works",
    "existing_browser_data_preserved",
    "byedpi_still_works",
    "offline_player_still_works",
)


def validate_report(report: object) -> list[str]:
    if not isinstance(report, dict):
        return ["Acceptance data is not a JSON object"]
    errors: list[str] = []
    if report.get("app_version") != "0.2.0":
        errors.append("Acceptance report must target v0.2.0")
    if report.get("extension_id") != REQUIRED_EXTENSION_ID:
        errors.append("Missing exact user-required AdBlock extension ID")
    if report.get("engine") != "android-chromium":
        errors.append("Native Android Chromium engine has not been verified")
    if report.get("test_environment") != "android-physical-device":
        errors.append("Android physical device test is required")
    if not isinstance(report.get("apk_sha256"), str) or len(
        report["apk_sha256"]
    ) != 64 or any(c not in "0123456789abcdef" for c in report["apk_sha256"]):
        errors.append("APK SHA-256 linking device evidence to build is missing")
    if not isinstance(report.get("device_model"), str) or not report[
        "device_model"
    ].strip():
        errors.append("Physical device model not recorded")
    checks = report.get("checks")
    if not isinstance(checks, dict):
        errors.append("Missing checks mapping")
    else:
        for key in REQUIRED_CHECKS:
            if checks.get(key) is not True:
                errors.append(f"Required Android AdBlock test did not pass: {key}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--report",
        type=Path,
        default=Path("build/reports/android_adblock_v0200.json"),
    )
    args = parser.parse_args()

    if not args.report.is_file():
        print(
            "::error title=AdBlock v0.2.0 acceptance::"
            "No Android device evidence found. "
            "A WebView APK is NOT a Chromium extension browser. "
            "Do not merge or release v0.2.0 until the real extension is "
            "installed, executed and tested on a physical device."
        )
        return 1
    try:
        report = json.loads(args.report.read_text(encoding="utf-8"))
    except (UnicodeError, json.JSONDecodeError) as exc:
        print(f"::error::Invalid AdBlock acceptance report: {exc}")
        return 1
    errors = validate_report(report)
    if errors:
        for error in errors:
            print(f"::error title=AdBlock v0.2.0 acceptance::{error}")
        return 1
    print(
        "AdBlock Android Chromium compatibility evidence validated. "
        "Check that the uploaded report is produced by trusted device tests."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
